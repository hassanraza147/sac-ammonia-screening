"""**Cell 2: Automated Structure Generation (SAC & Adsorbates)**
*Generates $N_4$-doped Graphene substrates, anchors transition metals ($\text{Fe, Co, Ni, Ru, Mo}$), and attaches $\text{N}_2$ adsorbates end-on and side-on.*
"""

import os
import numpy as np
import pandas as pd
from ase import Atoms
from ase.io import write

def create_n4_graphene_sac(metal_symbol="Fe", vacuum=10.0):
    """
    Constructs a 4x4 N4-doped graphene substrate with a single transition metal center.
    """
    # Base graphene lattice constant
    a = 2.46
    c = vacuum * 2.0

    # Generate a pristine 4x4 graphene supercell programmatically
    # Unit cell positions
    unit_positions = np.array([
        [0.0, 0.0, vacuum],
        [1.42, 0.0, vacuum]
    ])

    # Vectors for 4x4 supercell
    v1 = np.array([a, 0.0, 0.0])
    v2 = np.array([-a/2, a*np.sin(np.pi/3), 0.0])

    all_positions = []
    for i in range(4):
        for j in range(4):
            offset = i * v1 + j * v2
            all_positions.append(unit_positions[0] + offset)
            all_positions.append(unit_positions[1] + offset)

    atoms = Atoms(
        symbols='C32',
        positions=all_positions,
        cell=[[4*a, 0, 0], [-2*a, 4*a*np.sin(np.pi/3), 0], [0, 0, c]],
        pbc=[True, True, False]
    )

    # Center of the supercell
    pocket_center = np.array([2*a, 2*a*np.sin(np.pi/3), vacuum])

    # Find the 4 carbon atoms closest to the center to replace them with N
    distances = np.linalg.norm(atoms.positions - pocket_center, axis=1)
    closest_indices = np.argsort(distances)[:4]

    # Convert symbols to list to modify
    symbols = list(atoms.symbols)
    for idx in closest_indices:
        symbols[idx] = 'N'
    atoms.symbols = symbols

    # Place the metal atom at the pocket center
    metal_atom = Atoms(metal_symbol, positions=[pocket_center])
    atoms.extend(metal_atom)

    return atoms, pocket_center

def attach_n2_adsorbate(sac_atoms, metal_pos, mode="end-on", bond_length=2.1):
    """
    Attaches N2 adsorbate to the single metal site in end-on or side-on geometry.
    """
    adsorbate_system = sac_atoms.copy()

    if mode == "end-on":
        # N2 vertical above metal atom
        n1_pos = metal_pos + np.array([0, 0, bond_length])
        n2_pos = n1_pos + np.array([0, 0, 1.12])  # Standard N-N triple bond ~1.12 A
        n2_molecule = Atoms('N2', positions=[n1_pos, n2_pos])
    elif mode == "side-on":
        # N2 horizontal above metal atom
        n1_pos = metal_pos + np.array([-0.56, 0, bond_length])
        n2_pos = metal_pos + np.array([0.56, 0, bond_length])
        n2_molecule = Atoms('N2', positions=[n1_pos, n2_pos])

    adsorbate_system.extend(n2_molecule)
    return adsorbate_system

# Test structure batch generation
metals = ["Fe", "Co", "Ni", "Ru", "Mo"]
os.makedirs("structures_output", exist_ok=True)

print("--- Generating SAC Screening Library ---")
for m in metals:
    # 1. Bare SAC
    sac_base, center = create_n4_graphene_sac(metal_symbol=m)
    write(f"structures_output/{m}_N4_Graphene.xyz", sac_base)

    # 2. End-on N2 Adsorption
    sac_n2_end = attach_n2_adsorbate(sac_base, center, mode="end-on")
    write(f"structures_output/{m}_N4_Graphene_N2_endon.xyz", sac_n2_end)

    print(f"Generated structures for: {m}-N4/Graphene")

print("\nFiles saved to ./structures_output/")

"""**Cell 3: Feature Engineering & Adsorption Descriptor Calculator**
*Calculates metal d-electron counts, electronegativity differences, and metal-nitrogen coordination distances to feed your thermochemical activity model.*
"""

from pymatgen.core.periodic_table import Element

def extract_screening_descriptors(metal_symbol):
    """
    Extracts periodic table features to predict binding descriptors.
    """
    el = Element(metal_symbol)

    data = {
        "Metal": metal_symbol,
        "Atomic_Mass": el.atomic_mass,
        "Electronegativity": el.X,
        "d_electrons": el.mendeleev_no, # Valence context
        "Atomic_Radius": el.atomic_radius,
        "IE_1st_eV": el.ionization_energy
    }
    return data

descriptors = [extract_screening_descriptors(m) for m in metals]
df_descriptors = pd.DataFrame(descriptors)
df_descriptors.to_csv("structures_output/sac_descriptors.csv", index=False)

